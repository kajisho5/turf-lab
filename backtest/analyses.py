def _pop_control_html(slug):
    """人気で統制した表（bt_pop_control.py の出力）を記事に差し込む。

    生の集計だけ載せると「実績のある馬を買えば得」と読まれてしまう。
    人気を揃えると効果が消えることまで見せて初めて意味のある記事になる。
    """
    import json as _json
    import os as _os
    p = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "pop_control.json")
    if not _os.path.exists(p):
        return ""
    d = _json.load(open(p, encoding="utf-8"))
    ax = d.get("axes", {}).get(slug)
    if not ax:
        return ""
    order = ax["order"]
    head = "".join(f'<th class="n">{b}</th>' for b in order)
    body = ""
    for row in ax["rows"]:
        cells = ""
        for c in row["cells"]:
            if c["roi"] is None:
                cells += f'<td class="n dim">{c["n"]:,}R<br>件数不足</td>'
            else:
                # ★複勝だけ出さない★ 複勝は配当が削られるぶん差が潰れて見える。
                cells += (f'<td class="n">{c["n"]:,}R<br>'
                          f'単<strong>{c["tan_roi"]:.1f}%</strong><br>'
                          f'複<strong>{c["roi"]:.1f}%</strong></td>')
        body += f'<tr><td>{row["pop"]}</td>{cells}</tr>'
    return f"""<div class="scroll"><table class="zebra">
<tr><th>◎の人気</th>{head}</tr>
{body}
</table></div>
<p class="note">各マスは「レース数 ／ 単勝回収率 ／ 複勝回収率」。
{ax['min_n']:,}件に満たないマスは数字を出していません。
集計対象は◎{d['races']:,}レースです。
<strong>複勝だけでなく単勝も併記しています</strong>——
複勝はいちばん当たりやすい＝配当が削られる券種なので、
条件による差が実際より小さく見えるためです。</p>"""


