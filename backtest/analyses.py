"""記事のもとになる分析を登録する場所

★設計の考え方★
  記事を50本に増やしたい。ただし「増やすこと」が目的になると、
  中身の薄い記事で埋めることになり、このサイトの唯一の武器
  （検証結果を全部出す）が死ぬ。

  そこで
    ・1本 = 1つの問い + 1回の集計 + 結論（効かなかったも可）
    ・**サンプル数が足りないものは「判定不能」と自動で出す**（隠さない）
    ・集計は 176,819レースを**1パス**で全部同時に回す
      （分析ごとにファイルを舐めると1本増やすたびに数分待つことになる）

★1本の分析が返すもの★
  slug     URL（/data/{slug}/）
  title    見出し
  question 調べた問い
  rows     [(ラベル, 件数, 複勝率, 複勝ROI)]
  finding  結論の文（データから組み立てる。手書きの断定はしない）
  note     注意書き（任意）

★判定の基準を先に決めておく★
  MIN_N 未満の行は「判定不能」として数字を出さない。
  後から都合よく基準を動かせないよう、ここに定数として置く。
"""
import re
import unicodedata
from collections import defaultdict

MIN_N = 1000          # この件数未満の行は判定不能にする
ROI_NOISE = 2.0       # この幅（pt）以内の差は「差がない」と書く


# 評価する券種と、◎○▲△から組む買い目の形。
#
# ★形は先に決めて動かさない★
#   集計してから「いちばん良かった買い方」を選ぶと、それは検証ではなく
#   後知恵の選抜になる。◎を軸にした素直な形だけをここに固定する。
#
#   単勝   ◎              1点
#   複勝   ◎              1点
#   ワイド ◎-○ ◎-▲ ◎-△   3点
#   馬連   ◎-○ ◎-▲ ◎-△   3点
#   馬単   ◎→○ ◎→▲ ◎→△   3点
#   3連複  ◎-○-▲ ◎-○-△ ◎-▲-△  3点
#   3連単  ◎1着固定・○▲△の2-3着並べ替え   6点
#
# ROIの分母は必ず「点数 × 100円 × 買った全レース」。外れたレースも分母に入れる。
BETS = [
    ("tan",     "単勝",   1),
    ("fuku",    "複勝",   1),
    ("wide",    "ワイド", 3),
    ("umaren",  "馬連",   3),
    ("umatan",  "馬単",   3),
    ("sanpuku", "3連複",  3),
    ("santan",  "3連単",  6),
]


def _e():
    # [件数, 1着, 複勝内] + 券種ごとの払戻合計 + 券種ごとの最高配当1本
    #
    # ★最高配当を別に持つ理由★
    #   3連単のような当たりにくい券種のROIは、1本の大穴で丸ごと決まる。
    #   実測: 2000m以上の3連単6点買いは 2,059レースでROI120.3%だが、
    #   554,300円の的中1本を除くと75.4%まで落ちる。1本が投資総額の45%を占めていた。
    #   「100%超え」をそのまま載せると、このサイトの看板（盛らない）と真逆になる。
    #   最高配当を除いたROIを併記して、裾の重さが見えるようにする。
    return [0, 0, 0] + [0] * len(BETS) + [0] * len(BETS)


def _payout(pay, kind, axis, mates):
    """◎(axis)と相手(mates=○▲△)から、その券種の払戻合計を返す。

    ★点数ぶん買った前提★ 当たった1点だけでなく、買った全点を分母にする。
    """
    n = str(axis["n"])
    ms = [str(m["n"]) for m in mates]
    if kind == "tan":
        return (pay.get("tan") or {}).get(n, 0)
    if kind == "fuku":
        return (pay.get("fuku") or {}).get(n, 0)
    if kind == "wide":
        w = pay.get("wide") or {}
        tot = 0
        for m in ms:
            a, b = sorted((int(n), int(m)))
            tot += w.get(f"{a}-{b}", 0)
        return tot
    if kind in ("umaren", "sanpuku"):
        # 順不同。当たり組合せが自分の買い目に含まれていれば的中
        rec = pay.get(kind)
        if not rec:
            return 0
        combo, yen = rec
        cs = set(combo)
        if kind == "umaren":
            buys = [{n, m} for m in ms]
        else:
            buys = [{n, ms[a], ms[b]}
                    for a, b in ((0, 1), (0, 2), (1, 2)) if len(ms) > b]
        return yen if any(cs == set(b) for b in buys) else 0
    if kind in ("umatan", "santan"):
        rec = pay.get(kind)
        if not rec:
            return 0
        combo, yen = rec
        if kind == "umatan":
            buys = [[n, m] for m in ms]
        else:
            buys = []
            for a in range(len(ms)):
                for b in range(len(ms)):
                    if a != b:
                        buys.append([n, ms[a], ms[b]])
        return yen if any(list(combo) == b for b in buys) else 0
    return 0


class Analysis:
    """1本の記事に対応する集計。add() をレースごとに呼ばれる"""
    slug = ""
    title = ""
    question = ""
    note = ""
    order = None       # 表示順を固定したいとき

    def __init__(self):
        self.buckets = defaultdict(_e)

    def add(self, rc, hs, pay, axis):
        raise NotImplementedError

    def put(self, key, h, pay):
        """h を◎として1レース計上する。

        相手（○▲△）は collect() が渡してくれたスコア順の並び self._rk から取る。
        並びが無い場合は単勝・複勝だけ集計する（他券種は組めない）。
        """
        e = self.buckets[key]
        e[0] += 1
        e[1] += (h["rk"] == 1)
        e[2] += (h["rk"] <= 3)
        rk = getattr(self, "_rk", None) or []
        mates = [x for x in rk if x is not h][:3]
        nb = len(BETS)
        for i, (kind, _label, _pts) in enumerate(BETS):
            if kind not in ("tan", "fuku") and len(mates) < 3:
                continue
            y = _payout(pay, kind, h, mates)
            e[3 + i] += y
            if y > e[3 + nb + i]:
                e[3 + nb + i] = y      # その区分の最高配当1本

    def rows(self):
        keys = self.order or sorted(self.buckets)
        out = []
        for k in keys:
            if k not in self.buckets:
                continue
            v = self.buckets[k]
            n, win, hit = v[0], v[1], v[2]
            if n == 0:
                continue
            row = {"label": str(k), "n": n,
                   "win": 100 * win / n, "fuku": 100 * hit / n,
                   "ok": n >= MIN_N, "bets": {}, "bets_ex1": {}}
            nb = len(BETS)
            for i, (kind, label, pts) in enumerate(BETS):
                inv = pts * 100 * n
                row["bets"][kind] = 100 * v[3 + i] / inv
                # 最高配当1本を除いたROI（裾の重さを見るため）
                row["bets_ex1"][kind] = 100 * (v[3 + i] - v[3 + nb + i]) / inv
            row["roi"] = row["bets"]["fuku"]        # 従来の主軸（互換）
            row["tan_roi"] = row["bets"]["tan"]
            out.append(row)
        return out

    def finding(self, rows):
        """結論の文をデータから組み立てる。断定は成立するときだけ。

        ★複勝だけで判断しない★
          複勝はいちばん当たりやすい＝いちばん配当が削られる券種で、
          条件による差が潰れて見える。新馬戦の馬体重は3番人気の
          重い1/3 vs 軽い1/3 で複勝17.0pt差 → 単勝37.9pt差だった。
          かつて唯一の黒字とされた高知ファイナル⭐フォメも3連単で、
          （★その156%は再現できていない。後知恵の⭐で出ていた公算が大きい★）
          複勝ROIだけを見る手順では発見できない。

        ★ただし当たりにくい券種のROIは1本の大穴で決まる★
          2000m以上の3連単は2,059レースでROI120.3%だが、
          554,300円の的中1本を除くと75.4%。1本が投資総額の45%を占めていた。
          そのまま「100%超え」と書けば嘘になる。
          **最高配当1本を除いても成り立つか**を必ず併記する。
        """
        good = [r for r in rows if r["ok"]]
        if len(good) < 2:
            return "十分なサンプルが集まらず、比較できませんでした。"

        best = None
        for kind, label, _pts in BETS:
            hi = max(good, key=lambda r: r["bets"][kind])
            lo = min(good, key=lambda r: r["bets"][kind])
            d = hi["bets"][kind] - lo["bets"][kind]
            if best is None or d > best[0]:
                best = (d, kind, label, hi, lo)
        d, kind, label, hi, lo = best

        fuku_hi = max(good, key=lambda r: r["bets"]["fuku"])
        fuku_lo = min(good, key=lambda r: r["bets"]["fuku"])
        fd = fuku_hi["bets"]["fuku"] - fuku_lo["bets"]["fuku"]

        if d < ROI_NOISE:
            return (f"7つの券種すべてで調べましたが、回収率の差は"
                    f"いちばん開く{label}でも{d:.1f}ポイントでした。"
                    f"この条件では<strong>どの券種でもほとんど変わりません</strong>。")

        out = (f"いちばん差が出るのは<strong>{label}</strong>で、"
               f"「{hi['label']}」の{hi['bets'][kind]:.1f}%から"
               f"「{lo['label']}」の{lo['bets'][kind]:.1f}%まで"
               f"<strong>{d:.1f}ポイント</strong>開きます。")

        # ★大穴1本で作られた数字かどうかを必ず言う★
        ex1 = hi["bets_ex1"][kind]
        drop = hi["bets"][kind] - ex1
        if drop >= 10:
            out += (f"ただし{hi['label']}の{label}は、"
                    f"<strong>最も高い配当1本を除くと{ex1:.1f}%まで落ちます</strong>"
                    f"（{drop:.1f}ポイントぶんがその1本）。"
                    f"当たりにくい券種の回収率は大穴1本で決まってしまうので、"
                    f"この数字は<strong>そのままでは使えません</strong>。")
        elif hi["bets"][kind] >= 100:
            out += (f"最も高い配当1本を除いても{ex1:.1f}%を保っています。")

        if kind != "fuku":
            if fd < ROI_NOISE:
                out += (f"いっぽう複勝ではほとんど差がありません"
                        f"（最大{fd:.1f}ポイント）。"
                        f"<strong>複勝だけ見ていると気づけない差</strong>です。")
            else:
                out += f"複勝でも{fd:.1f}ポイントの差があります。"
        return out


