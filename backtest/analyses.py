class _TopN(Analysis):
    """出走数の多い上位N件だけを並べる分析の共通部分

    ★上位だけに絞る理由★
      騎手も種牡馬も裾が非常に長い（1回しか出ていない名前が大量にある）。
      全部並べると読めないうえ、少数のサンプルで極端な回収率が出て
      「この騎手は300%」のような誤読を生む。
      出走数上位に限り、さらに MIN_N の判定も併用する。
    """
    idx = 0        # aux のどの要素を見るか
    top = 20

    def add(self, rc, hs, pay, axis):
        a = (rc.get("aux") or {}).get(str(int(axis["n"])))
        if not a:
            return
        v = a[self.idx]
        if v:
            self.put(v, axis, pay)

    def rows(self):
        # ★親と同じ形を返すこと★ ここだけ独自に展開していたため、
        #   バケツに単勝を足したときに落ちた（3要素で受けていた）。
        rs = []
        for k, v in self.buckets.items():
            n, win, hit = v[0], v[1], v[2]
            if n == 0:
                continue
            row = {"label": k, "n": n, "win": 100 * win / n,
                   "fuku": 100 * hit / n, "ok": n >= MIN_N,
                   "bets": {}, "bets_ex1": {}}
            nb = len(BETS)
            for i, (kind, label, pts) in enumerate(BETS):
                inv = pts * 100 * n
                row["bets"][kind] = 100 * v[3 + i] / inv
                row["bets_ex1"][kind] = 100 * (v[3 + i] - v[3 + nb + i]) / inv
            row["roi"] = row["bets"]["fuku"]
            row["tan_roi"] = row["bets"]["tan"]
            rs.append(row)
        rs.sort(key=lambda r: -r["n"])
        return rs[:self.top]


